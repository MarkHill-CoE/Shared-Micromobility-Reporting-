import nodemailer from 'nodemailer';
import type { IssueReport, VendorEmailDispatch } from '../types/report.ts';

export interface VendorRoute {
  vendor: string;
  recipient: string;
}

/**
 * Resolves the vendor name and destination email address from Section 3 Question 5 selection.
 */
export function resolveVendorRoute(identifyingColours: string): VendorRoute {
  const normalized = (identifyingColours || '').trim();

  if (
    normalized === 'Bird - Blue or Black E-Scooters and Blue and Black E-Bikes' ||
    normalized.toLowerCase().startsWith('bird')
  ) {
    return {
      vendor: 'Bird',
      recipient: 'mark.hill@edmonton.ca',
    };
  }

  if (
    normalized === 'Lime - White and Green E-Scooters and E-Bikes' ||
    normalized.toLowerCase().startsWith('lime')
  ) {
    return {
      vendor: 'Lime',
      recipient: 'mark.hill@edmonton.ca',
    };
  }

  if (
    normalized === 'Private E-Scooter or E-Bike' ||
    normalized.toLowerCase().includes('private')
  ) {
    return {
      vendor: 'Private E-Scooter or E-Bike',
      recipient: 'mark.hill@edmonton.ca',
    };
  }

  return {
    vendor: normalized.split(' - ')[0] || 'Unidentified Vendor',
    recipient: 'mark.hill@edmonton.ca',
  };
}

/**
 * Formats selected issue types into a concise label for email subject & body.
 */
export function formatIssueTypeSummary(issueTypes: IssueReport['issueTypes']): string {
  const types: string[] = [];
  if (issueTypes?.improperParking) types.push('Improper Parking');
  if (issueTypes?.damageMalfunction) types.push('Damage or Malfunction');
  if (issueTypes?.safetyConcerns) types.push('Safety Concerns');
  if (issueTypes?.other) {
    types.push(issueTypes.otherText?.trim() ? `Other (${issueTypes.otherText.trim()})` : 'Other');
  }
  return types.length > 0 ? types.join(', ') : 'General Issue';
}

/**
 * Formats a timestamp cleanly in Edmonton local time (America/Edmonton) for the email subject.
 */
export function formatEdmontonTimestamp(isoDateString?: string): string {
  const date = isoDateString ? new Date(isoDateString) : new Date();
  const safeDate = Number.isNaN(date.getTime()) ? new Date() : date;

  const parts = new Intl.DateTimeFormat('en-CA', {
    timeZone: 'America/Edmonton',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
    hour12: false,
    timeZoneName: 'short',
  }).formatToParts(safeDate);

  const get = (type: string) => parts.find((p) => p.type === type)?.value || '';
  return `${get('year')}-${get('month')}-${get('day')} ${get('hour')}:${get('minute')}:${get('second')} ${get('timeZoneName')}`.trim();
}

/**
 * Builds the exact required email subject line:
 * Edmonton -<vendor> Immediate Attention Required -<Type of Issue>-<Time Stamp>
 */
export function buildVendorEmailSubject(report: IssueReport): string {
  const { vendor } = resolveVendorRoute(report.identifyingColours);
  const issueType = formatIssueTypeSummary(report.issueTypes);
  const timestamp = formatEdmontonTimestamp(report.createdAt);

  return `Edmonton -${vendor} Immediate Attention Required -${issueType}-${timestamp}`;
}

/**
 * Builds the plain-text and HTML email body containing the PII-scrubbed description.
 */
function buildVendorEmailBody(report: IssueReport, vendor: string, issueType: string): {
  text: string;
  html: string;
} {
  const piiNotice = report.piiScrubbing?.scrubbed
    ? `Yes (${report.piiScrubbing.redactedCount} redaction(s): ${report.piiScrubbing.redactedCategories.join(', ')})`
    : 'Verified (no PII detected)';

  const gpsLine = report.gpsCoordinates
    ? `${report.gpsCoordinates.latitude}, ${report.gpsCoordinates.longitude} (±${report.gpsCoordinates.accuracy ?? 0}m)`
    : 'Not captured';

  const text = [
    'CITY OF EDMONTON - MICROMOBILITY ISSUE DISPATCH',
    '============================================================',
    `Tracking Code:      ${report.trackingCode}`,
    `Report ID:          ${report.id}`,
    `Vendor / Category:  ${vendor} (${report.identifyingColours})`,
    `Vehicle ID Number:  ${report.vehicleIdNumber || 'Not provided'}`,
    `Type of Issue:      ${issueType}`,
    `Incident Date/Time: ${report.incidentDate} ${report.incidentTime || ''}`.trim(),
    `Location Details:   ${report.locationDetails}`,
    `GPS Coordinates:    ${gpsLine}`,
    `Attachment:         ${report.attachment ? `${report.attachment.name} (${(report.attachment.size / 1024).toFixed(0)} KB)` : 'None'}`,
    `PII Scrubbing:      ${piiNotice}`,
    '',
    'DESCRIPTION OF ISSUE (PII SCRUBBED):',
    '------------------------------------------------------------',
    report.issueDescription,
    '------------------------------------------------------------',
    '',
    'This automated notice was generated by the City of Edmonton Rental E-Scooter & E-Bike Issue Reporting portal.',
  ].join('\n');

  const escapeHtml = (val: string) =>
    val
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');

  const html = `
    <div style="font-family: 'Open Sans', Arial, sans-serif; color: #222222; max-width: 640px; margin: 0 auto; border: 1px solid #D0D7DE; border-radius: 6px; overflow: hidden;">
      <div style="background-color: #005087; color: #FFFFFF; padding: 16px 20px;">
        <div style="font-size: 11px; text-transform: uppercase; letter-spacing: 0.08em; opacity: 0.9;">City of Edmonton · Micromobility Management</div>
        <h2 style="margin: 4px 0 0; font-size: 18px;">Immediate Attention Required — ${escapeHtml(vendor)}</h2>
      </div>
      <div style="padding: 20px; background-color: #FFFFFF;">
        <table style="width: 100%; border-collapse: collapse; font-size: 13px; margin-bottom: 16px;">
          <tr><td style="padding: 6px 0; color: #767676; width: 160px;"><strong>Tracking Code</strong></td><td style="padding: 6px 0; font-family: monospace; font-weight: bold;">${escapeHtml(report.trackingCode)}</td></tr>
          <tr><td style="padding: 6px 0; color: #767676;"><strong>Vendor / Selection</strong></td><td style="padding: 6px 0;">${escapeHtml(report.identifyingColours)}</td></tr>
          <tr><td style="padding: 6px 0; color: #767676;"><strong>Vehicle ID</strong></td><td style="padding: 6px 0; font-family: monospace;">${escapeHtml(report.vehicleIdNumber || 'Not provided')}</td></tr>
          <tr><td style="padding: 6px 0; color: #767676;"><strong>Type of Issue</strong></td><td style="padding: 6px 0;">${escapeHtml(issueType)}</td></tr>
          <tr><td style="padding: 6px 0; color: #767676;"><strong>Incident Date &amp; Time</strong></td><td style="padding: 6px 0;">${escapeHtml(report.incidentDate)} ${escapeHtml(report.incidentTime || '')}</td></tr>
          <tr><td style="padding: 6px 0; color: #767676;"><strong>Location Details</strong></td><td style="padding: 6px 0;">${escapeHtml(report.locationDetails)}</td></tr>
          <tr><td style="padding: 6px 0; color: #767676;"><strong>GPS Coordinates</strong></td><td style="padding: 6px 0; font-family: monospace;">${escapeHtml(gpsLine)}</td></tr>
          <tr><td style="padding: 6px 0; color: #767676;"><strong>PII Scrubbing</strong></td><td style="padding: 6px 0; color: #008269; font-weight: 600;">${escapeHtml(piiNotice)}</td></tr>
        </table>
        <div style="background-color: #F3F5F7; border-left: 4px solid #005087; padding: 12px 14px; border-radius: 4px;">
          <div style="font-size: 11px; text-transform: uppercase; letter-spacing: 0.05em; color: #005087; font-weight: bold; margin-bottom: 6px;">Description of Issue (PII Scrubbed)</div>
          <div style="font-size: 13px; line-height: 1.5; white-space: pre-wrap;">${escapeHtml(report.issueDescription)}</div>
        </div>
      </div>
    </div>
  `;

  return { text, html };
}

/**
 * Prepares and attempts to send the vendor notification email via configured SMTP.
 * Never fabricates delivery: returns 'pending_smtp' if SMTP_HOST is not configured.
 */
export async function dispatchVendorEmail(report: IssueReport): Promise<VendorEmailDispatch> {
  const { vendor, recipient } = resolveVendorRoute(report.identifyingColours);
  const issueType = formatIssueTypeSummary(report.issueTypes);
  const subject = buildVendorEmailSubject(report);
  const { text, html } = buildVendorEmailBody(report, vendor, issueType);

  const smtpHost = (process.env.SMTP_HOST || '').trim();
  const smtpPort = Number(process.env.SMTP_PORT || 587);
  const smtpSecure = process.env.SMTP_SECURE === 'true' || smtpPort === 465;
  const smtpUser = (process.env.SMTP_USER || '').trim();
  const smtpPass = (process.env.SMTP_PASS || '').trim();
  const smtpFrom = (process.env.SMTP_FROM || smtpUser || 'micromobility-intake@edmonton.ca').trim();

  if (!smtpHost) {
    console.info(
      `[Vendor Email Queue] SMTP_HOST not configured. Prepared email for ${recipient} | Subject: "${subject}"`
    );
    return {
      vendor,
      recipient,
      subject,
      body: text,
      status: 'pending_smtp',
      error:
        'Automated SMTP delivery requires SMTP_HOST (and credentials) in environment variables. Prepared email payload is saved for review or manual dispatch.',
    };
  }

  try {
    const transporter = nodemailer.createTransport({
      host: smtpHost,
      port: smtpPort,
      secure: smtpSecure,
      auth: smtpUser && smtpPass ? { user: smtpUser, pass: smtpPass } : undefined,
    });

    const attachments: Array<{ filename: string; path: string }> = [];
    if (report.attachment?.dataUrl && report.attachment.name) {
      attachments.push({
        filename: report.attachment.name,
        path: report.attachment.dataUrl,
      });
    }

    const info = await transporter.sendMail({
      from: smtpFrom,
      to: recipient,
      subject,
      text,
      html,
      attachments,
    });

    console.info(`[Vendor Email Sent] To: ${recipient} | Subject: "${subject}" | MessageId: ${info.messageId}`);

    return {
      vendor,
      recipient,
      subject,
      body: text,
      status: 'sent',
      sentAt: new Date().toISOString(),
      messageId: info.messageId,
    };
  } catch (err: any) {
    console.error('[Vendor Email Failed]', err);
    return {
      vendor,
      recipient,
      subject,
      body: text,
      status: 'failed',
      error: err?.message || 'SMTP transport error',
    };
  }
}
